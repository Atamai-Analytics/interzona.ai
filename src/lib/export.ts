import type { Conversation, Evidence, Message } from "./types";

export function slug(s: string, max = 60) {
  return s.replace(/[^a-z0-9]+/gi, "-").replace(/^-+|-+$/g, "").slice(0, max) || "conversation";
}

export function downloadText(filename: string, text: string, mime: string) {
  // A byte-order mark tells phone viewers and older editors the file is UTF-8 (otherwise symbols such as \u00b1 can be misread). Only for Markdown: CSV downloads handle this themselves.
  const blob = new Blob(mime.startsWith("text/markdown") ? ["\ufeff", text] : [text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function sourcesMarkdown(evidence: Evidence[] | undefined): string {
  if (!evidence?.length) return "";
  const byDoc = new Map<string, number[]>();
  const web: string[] = [];
  const data: string[] = [];
  for (const e of evidence) {
    if (e.kind === "document") {
      const pages = byDoc.get(e.title) ?? [];
      if (e.page !== undefined && !pages.includes(e.page)) pages.push(e.page);
      byDoc.set(e.title, pages);
    } else if (e.kind === "web") web.push(`[${e.title}](${e.url})`);
    else data.push(e.detail ? `${e.label} (${e.detail})` : e.label);
  }
  const lines: string[] = ["", "**Sources**", ""];
  for (const d of new Set(data)) lines.push(`- Data: ${d}`);
  for (const [t, p] of byDoc) lines.push(`- ${t}${p.length ? `, p. ${p.sort((a, b) => a - b).join(", ")}` : ""}`);
  for (const w of new Set(web)) lines.push(`- Web: ${w}`);
  return lines.join("\n");
}

function assistantMarkdown(m: Message): string {
  const parts: string[] = [m.content.trim() || "_(no answer)_"];
  for (const d of m.datasets ?? []) if (d.chart) parts.push(`_Chart shown in the app: ${d.title} (${d.chart.unit})._`);
  for (const mp of m.maps ?? []) {
    const rows = mp.points.slice(0, 25).map((p) => `| ${p.label.replace(/\|/g, "/")} | ${p.group.replace(/\|/g, "/")} | ${p.lat.toFixed(3)} | ${p.lon.toFixed(3)} |`);
    parts.push([`_Map shown in the app: ${mp.title} (${mp.points.length} places${mp.points.length > 25 ? ", first 25 listed" : ""})._`, "", "| Place | Group | Latitude | Longitude |", "|---|---|---|---|", ...rows].join("\n"));
  }
  for (const img of m.images ?? []) parts.push(`![${img.caption}](data:${img.mimeType};base64,${img.base64})`);
  if (m.notice) parts.push(`_${m.notice}_`);
  if (m.stopped) parts.push("_Stopped before finishing._");
  const src = sourcesMarkdown(m.evidence);
  if (src) parts.push(src);
  return parts.join("\n\n");
}

export function toMarkdown(c: Conversation): string {
  const when = new Date(c.updatedAt).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" });
  const out: string[] = [`# ${c.title}`, "", `_Critical Minerals AI Assistant · ${when}_`, ""];
  for (const m of c.messages) {
    if (m.role === "user") out.push("## Question", "", m.content.trim(), "");
    else out.push("## Answer", "", assistantMarkdown(m), "");
  }
  out.push("---", "", "_Generated by an AI assistant from the underlying datasets and documents; check important figures against the sources listed._", "");
  return out.join("\n");
}
